package types

import (
	"strings"
	"time"

	"github.com/biox-dev/gobrave/internal/utils"
	"gorm.io/gorm"
)

// DatasetKeyDatabases is the dataset_key of the project's default database
// directory. The dataset is provisioned on demand by the
// get_project_database_path agent tool and holds reference databases shared by
// the project's analysis scripts.
const DatasetKeyDatabases = "DATABASES"

type Dataset struct {
	ID int64 `json:"id,string" gorm:"primaryKey;type:bigint;autoIncrement:false"`

	DatasetName string `json:"dataset_name" gorm:"type:varchar(255)"`

	// DatasetKey is a stable business key used to look up well-known datasets
	// the system provisions on demand, e.g. DatasetKeyDatabases ("DATABASES")
	// for the project's reference database directory. User-created datasets
	// leave it empty. In practice it is unique per project (go_dataset itself
	// has no project column; the binding lives in go_project_dataset).
	DatasetKey string `json:"dataset_key" gorm:"type:varchar(64);index"`

	Description string `json:"description" gorm:"type:text"`

	Metadata string `json:"metadata" gorm:"type:text"`

	// Path is the dataset workspace directory (utils.GetDatasetDir). It is
	// derived at read time from the active project and is never persisted.
	Path string `json:"path,omitempty" gorm:"-"`

	CreatedAt time.Time `json:"created_at"`

	UpdatedAt time.Time `json:"updated_at"`
}

func (Dataset) TableName() string {
	return "go_dataset"
}

func (t *Dataset) BeforeCreate(_ *gorm.DB) error {
	if t.ID == 0 {
		t.ID = utils.GenerateID()
	}
	return nil
}

// CreateDatasetRequest is the payload for creating a dataset. The primary key
// is generated by the application, callers only provide business fields.
type CreateDatasetRequest struct {
	DatasetName string `json:"dataset_name" binding:"required"`
	// DatasetKey is optional; leave it empty for ordinary user datasets.
	DatasetKey  string `json:"dataset_key"`
	Description string `json:"description"`
	Metadata    string `json:"metadata"`
}

// ToDataset converts the request into a Dataset entity. ID and audit fields are
// intentionally left zero so that BeforeCreate generates them.
func (r *CreateDatasetRequest) ToDataset() *Dataset {
	if r == nil {
		return &Dataset{}
	}

	return &Dataset{
		DatasetName: strings.TrimSpace(r.DatasetName),
		DatasetKey:  strings.TrimSpace(r.DatasetKey),
		Description: r.Description,
		Metadata:    r.Metadata,
	}
}

// UpdateDatasetRequest is the payload for updating a dataset. ID identifies the
// record to update and is always required.
type UpdateDatasetRequest struct {
	ID          int64  `json:"id,string" binding:"required"`
	DatasetName string `json:"dataset_name" binding:"required"`
	DatasetKey  string `json:"dataset_key"`
	Description string `json:"description"`
	Metadata    string `json:"metadata"`
}

// ToDataset converts the request into a Dataset entity for the update path.
func (r *UpdateDatasetRequest) ToDataset() *Dataset {
	if r == nil {
		return &Dataset{}
	}

	return &Dataset{
		ID:          r.ID,
		DatasetName: strings.TrimSpace(r.DatasetName),
		DatasetKey:  strings.TrimSpace(r.DatasetKey),
		Description: r.Description,
		Metadata:    r.Metadata,
	}
}

type ProjectDataset struct {
	ID int64 `json:"id,string" gorm:"primaryKey;type:bigint;autoIncrement:false"`

	ProjectID int64 `json:"project_id,string" gorm:"index;not null"`

	DatasetID int64 `json:"dataset_id,string" gorm:"index;not null"`

	// Path is the bound dataset's workspace directory
	// (utils.GetDatasetDir(baseDir, project_id, dataset_id)). It is derived at
	// read time and is never persisted.
	Path string `json:"path,omitempty" gorm:"-"`

	CreatedAt time.Time `json:"created_at"`
}

func (ProjectDataset) TableName() string {
	return "go_project_dataset"
}

func (t *ProjectDataset) BeforeCreate(_ *gorm.DB) error {
	if t.ID == 0 {
		t.ID = utils.GenerateID()
	}
	return nil
}

// QueryDataset defines optional dataset filters for list/page APIs.
type QueryDataset struct {
	ID *int64 `json:"id,string,omitempty"`

	DatasetName string `json:"dataset_name,omitempty"`

	DatasetKey string `json:"dataset_key,omitempty"`

	Description string `json:"description,omitempty"`

	Metadata string `json:"metadata,omitempty"`
}

func (q *QueryDataset) GetDatasetKey() string {
	if q == nil {
		return ""
	}
	return strings.TrimSpace(q.DatasetKey)
}

func (q *QueryDataset) GetDatasetName() string {
	if q == nil {
		return ""
	}
	return strings.TrimSpace(q.DatasetName)
}

func (q *QueryDataset) GetDescription() string {
	if q == nil {
		return ""
	}
	return strings.TrimSpace(q.Description)
}

func (q *QueryDataset) GetMetadata() string {
	if q == nil {
		return ""
	}
	return strings.TrimSpace(q.Metadata)
}
